$dev = [Collections.Generic.List[string]]::new()
$blind = [Collections.Generic.List[string]]::new()
$index = 0
foreach ($category in $groups.Keys) {
    $categoryIndex = 0
    foreach ($pair in $groups[$category]) {
        $index++
        $categoryIndex++
        $parts = $pair -split '\|', 2
        $split = if ($categoryIndex -le 4) { 'dev' } else { 'blind' }
        $record = [ordered]@{
            id = "qpv2-$('{0:D4}' -f $index)"
            rawInput = $parts[1]
            expectedTexts = @($parts[0])
            category = $category
            tags = @('clean', $(if ($category.StartsWith('domain_')) { 'optional_domain' } elseif ($category -eq 'hotword') { 'time_sensitive' } else { 'base' }))
            source = $sourceId
            split = $split
        }
        $line = $record | ConvertTo-Json -Compress -Depth 4
        if ($split -eq 'dev') { $dev.Add($line) } else { $blind.Add($line) }
    }
}
[IO.File]::WriteAllLines((Join-Path $output 'dev.jsonl'), $dev, $utf8)
[IO.File]::WriteAllLines((Join-Path $output 'blind.jsonl'), $blind, $utf8)

